  const DICTS = { en, uk };

  function pickLang() {
    try {
      const q = new URLSearchParams(location.search).get('lang');
      if (q && DICTS[q]) { localStorage.setItem('lang', q); return q; }
      const saved = localStorage.getItem('lang');
      if (saved && DICTS[saved]) return saved;
    } catch {}
    return DEFAULT_LANG;
  }

  const LANG = pickLang();
  if (typeof document !== 'undefined') document.documentElement.lang = LANG;

  const t = (key, params = {}) => {
    const s = DICTS[LANG][key] ?? en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (k in params ? params[k] : ''));
  };
  const has = (key) => key in DICTS[LANG] || key in en;

  root.I18N = { LANG, t, has };
